def write_preregistration(output: Path) -> Path:
    """Write the scoring and verdict declaration before reading a frame."""

    output.mkdir(parents=True, exist_ok=True)
    path = output / PREREGISTRATION_NAME
    path.write_text(json.dumps(preregistration(), indent=2, sort_keys=True) + "\n")
    return path


def require_preregistration(path: Path) -> str:
    """Return the declaration digest, failing closed on any mutation."""

    if not path.is_file():
        raise RuntimeError("root-existence criterion must be preregistered")
    encoded = path.read_bytes()
    if json.loads(encoded) != preregistration():
        raise RuntimeError("on-disk root-existence preregistration does not match")
    return hashlib.sha256(encoded).hexdigest()


def region_masks(core: np.ndarray) -> dict[str, np.ndarray]:
    """Partition the whole grid into core, one-cell boundary, and exterior."""

    core = np.asarray(core, dtype=bool)
    structure = np.ones((3, 3), dtype=bool)
    eroded = binary_erosion(core, structure=structure, border_value=0)
    band = binary_dilation(core, structure=structure) & ~eroded
    exterior = ~(eroded | band)
    if np.any((eroded.astype(int) + band.astype(int) + exterior.astype(int)) != 1):
        raise RuntimeError("residual region masks do not form a partition")
    return {
        "plasma_interior": eroded,
        "boundary_band": band,
        "exterior": exterior,
    }


def residual_metrics(
    residual: np.ndarray,
    label_range: float,
    regions: dict[str, np.ndarray],
) -> dict[str, Any]:
    """Return absolute, fractional, and exactly closed regional residuals."""

    residual = np.asarray(residual, dtype=float)
    energy = residual**2
    total = float(np.sum(energy))
    if total <= np.finfo(float).tiny:
        fractions = {name: 0.0 for name in regions}
        fractions["exterior"] = 1.0
    else:
        fractions = {
            name: float(np.sum(energy[mask]) / total) for name, mask in regions.items()
        }
        closure = sum(fractions.values())
        fractions["exterior"] += 1.0 - closure
    rms = float(np.sqrt(np.mean(energy)))
    return {
        "rms_wb_total": rms,
        "fractional_rms": rms / abs(label_range),
        "maximum_absolute_wb_total": float(np.max(np.abs(residual))),
        "regional_squared_residual_fractions": fractions,
        "regional_fraction_sum": float(sum(fractions.values())),
    }


def border_values(field: np.ndarray) -> np.ndarray:
    """Return clockwise grid-border samples with each corner included once."""

    field = np.asarray(field)
    return np.r_[
        field[0, :-1],
        field[:-1, -1],
        field[-1, :0:-1],
        field[:0:-1, 0],
    ]


def border_coordinates(radius: np.ndarray, height: np.ndarray) -> np.ndarray:
    """Return physical coordinates in the same order as :func:`border_values`."""

    r, z = np.meshgrid(radius, height, indexing="ij")
    return np.c_[border_values(r), border_values(z)]


def boundary_discrepancy(
    labelled_per_radian: np.ndarray,
    coil_per_radian: np.ndarray,
    gauge_per_radian: float,
) -> dict[str, Any]:
    """Compare literal labelled and coil flux around the released grid border."""

    label = border_values(labelled_per_radian)
    coil = border_values(coil_per_radian)

    def metrics(difference: np.ndarray) -> dict[str, float]:
        label_range = float(np.ptp(labelled_per_radian))
        rms = float(np.sqrt(np.mean(difference**2)))
        return {
            "signed_mean_wb_per_radian": float(np.mean(difference)),
            "rms_wb_per_radian": rms,
            "maximum_absolute_wb_per_radian": float(np.max(np.abs(difference))),
            "fractional_rms_of_labelled_range": rms / label_range,
        }

    before = label - coil
    after = label - (coil + gauge_per_radian)
    return {
        "gauge_applied_to_coil_wb_per_radian": gauge_per_radian,
        "before_gauge": metrics(before),
        "after_gauge": metrics(after),
        "after_gauge_samples_wb_per_radian": after.tolist(),
    }


def component_verdict(
    fixed_fractional_rms: float,
    vacuum_fractional_rms: float,
    gauged_boundary_fraction: float,
) -> dict[str, Any]:
    """Attribute a residual using the preregistered magnitude split."""

    denominator = fixed_fractional_rms + vacuum_fractional_rms
    if denominator <= np.finfo(float).tiny:
        fixed_share = vacuum_share = 0.5
    else:
        fixed_share = fixed_fractional_rms / denominator
        vacuum_share = vacuum_fractional_rms / denominator
    if (
        vacuum_share >= DOMINANT_COMPONENT_FRACTION
        and gauged_boundary_fraction > NEARBY_ROOT_MAXIMUM_FRACTIONAL_RMS
    ):
        verdict = "vacuum-field-dominated"
    elif fixed_share >= DOMINANT_COMPONENT_FRACTION:
        verdict = "flux-function-dominated"
    else:
        verdict = "both"
    return {
        "verdict": verdict,
        "fixed_boundary_share": fixed_share,
        "vacuum_difference_share": vacuum_share,
        "share_sum": fixed_share + vacuum_share,
        "gauged_boundary_fractional_rms": gauged_boundary_fraction,
    }


def _profile_source(
    row: dict[str, Any], frame: int, radius: np.ndarray, height: np.ndarray
) -> tuple[np.ndarray, int, np.ndarray]:
    """Evaluate profiles extracted from the label back on that label."""

    label_total = corpus_flux_to_nova_total(
        np.asarray(row["efit_psirz"][frame], dtype=float)
    ).T
    psi_norm = normalised_flux(row, frame).T
    core = _plasma_mask(row, frame, radius, height)
    extraction = extract_flux_functions(
        radius,
        height,
        label_total,
        psi_norm,
        plasma_mask=core,
        min_samples=6,
    )
    reliable = extraction.reliable & np.isfinite(
        extraction.p_prime + extraction.ff_prime
    )
    if np.count_nonzero(reliable) < 2:
        raise RuntimeError("fewer than two reliable extracted profile surfaces")
    p_prime = np.interp(
        psi_norm, extraction.psi_norm[reliable], extraction.p_prime[reliable]
    )
    ff_prime = np.interp(
        psi_norm, extraction.psi_norm[reliable], extraction.ff_prime[reliable]
    )
    radius_map = np.broadcast_to(radius[:, None], psi_norm.shape)
    source = np.zeros_like(label_total)
    active = core & extraction.current.valid & np.isfinite(p_prime + ff_prime)
    active &= np.isfinite(psi_norm) & (psi_norm >= 0.0) & (psi_norm <= 1.0)
    source[active] = grad_shafranov_source(
        radius_map[active], p_prime[active], ff_prime[active]
    )
    return source, int(np.count_nonzero(reliable)), label_total


def evaluate_frame(
    row: dict[str, Any],
    frame: int,
    plasma_response: np.ndarray,
) -> tuple[dict[str, Any], dict[str, np.ndarray]]:
    """Evaluate all residuals at one unchanged labelled map."""

    radius, height = canonical_axes(row)
    operator = _operator(radius, height)
    source, reliable, label_total = _profile_source(row, frame, radius, height)
    core = _plasma_mask(row, frame, radius, height)
    regions = region_masks(core)
    label_range = float(np.ptp(label_total))

    source_row = str(row.get("_source_path", "corpus row"))
    description = dataset_machine_description(row, source_row=source_row).physical
    response = vacuum_response(description, radius, height)
    coil_total_zr = vacuum_psi(row, description, response)[frame]
    coil_total = np.asarray(coil_total_zr, dtype=float).T

    direct = apply_delta_star(radius, height, label_total)
    direct_solution = operator.solve(direct.delta_star_flux, label_total)
    fixed_solution = operator.solve(source, label_total)
    free_solution = operator.solve(source, coil_total)
    direct_residual = direct_solution - label_total
    fixed_residual = fixed_solution - label_total
    free_residual = free_solution - label_total
    vacuum_difference = free_solution - fixed_solution

    label_per_radian = np.asarray(row["efit_psirz"][frame], dtype=float)
    coil_per_radian = nova_total_flux_to_corpus(coil_total_zr)
    plasma = project_label_plasma(row, frame, radius, height, plasma_response)
    remainder = label_per_radian - plasma.plasma_flux_per_radian
    _r2, _error, _total, gauge, _residual = gauge_r_squared(remainder, coil_per_radian)
    boundary = boundary_discrepancy(
        label_per_radian.T,
        coil_per_radian.T,
        gauge,
    )

    residuals = {
        "direct_operator_fixed_boundary_control": residual_metrics(
            direct_residual, label_range, regions
        ),
        "fixed_boundary_profile": residual_metrics(
            fixed_residual, label_range, regions
        ),
        "free_boundary_profile": residual_metrics(free_residual, label_range, regions),
        "free_minus_fixed_vacuum_difference": residual_metrics(
            vacuum_difference, label_range, regions
        ),
    }
    verdict = component_verdict(
        residuals["fixed_boundary_profile"]["fractional_rms"],
        residuals["free_minus_fixed_vacuum_difference"]["fractional_rms"],
        boundary["after_gauge"]["fractional_rms_of_labelled_range"],
    )
    record = {
        "shot": Path(source_row).name,
        "frame": frame,
        "time_ms": float(row["efit_times"][frame]),
        "evaluation_point": "labelled psi map unchanged",
        "root_find_performed": False,
        "coefficients_fitted": 0,
        "coil_currents_adjusted": False,
        "reliable_extraction_surfaces": reliable,
        "labelled_psi_range_wb_total": label_range,
        "residuals": residuals,
        "boundary_flux_discrepancy": boundary,
        "attribution": verdict,
        "nearby_root_admitted": bool(
            residuals["free_boundary_profile"]["fractional_rms"]
            <= NEARBY_ROOT_MAXIMUM_FRACTIONAL_RMS
        ),
    }
    fields = {
        "radius": radius,
        "height": height,
        "label_total": label_total,
        "core": core,
        "free_residual_per_radian": nova_total_flux_to_corpus(free_residual.T).T,
        "fixed_residual_per_radian": nova_total_flux_to_corpus(fixed_residual.T).T,
        "vacuum_difference_per_radian": nova_total_flux_to_corpus(
            vacuum_difference.T
        ).T,
        "border_coordinate": border_coordinates(radius, height),
        "border_difference": np.asarray(boundary["after_gauge_samples_wb_per_radian"]),
    }
    return record, fields


def _rectangle_vertices(geometry: Any) -> np.ndarray:
    rectangle = geometry.rectangle
    r = float(rectangle.r)
    z = float(rectangle.z)
    half_width = 0.5 * float(rectangle.width)
    half_height = 0.5 * float(rectangle.height)
    return np.asarray(
        [
            (r - half_width, z - half_height),
            (r + half_width, z - half_height),
            (r + half_width, z + half_height),
            (r - half_width, z + half_height),
        ]
    )


def omitted_coil_envelope(
    coordinate: np.ndarray, measured_rms_wb_per_radian: float
) -> dict[str, Any]:
    """Compare the missing-coil maximum-amplitude envelope with the discrepancy."""

    import imas

    contributions = []
    with imas.DBEntry(NETCDF_ENTRY, "r", dd_version=NETCDF_DD_VERSION) as entry:
        active = entry.get("pf_active", autoconvert=False)
        coils = {str(coil.name): coil for coil in active.coil}
        for name in OMITTED_COILS:
            coil = coils[name]
            response = np.zeros(len(coordinate), dtype=float)
            for element in coil.element:
                geometry = element.geometry
                geometry_type = int(geometry.geometry_type)
                if geometry_type == 1:
                    vertices = np.c_[
                        np.asarray(geometry.outline.r, dtype=float),
                        np.asarray(geometry.outline.z, dtype=float),
                    ]
                elif geometry_type == 2:
                    vertices = _rectangle_vertices(geometry)
                else:
                    raise ValueError(
                        f"unsupported geometry type {geometry_type} for {name}"
                    )
                response += (
                    float(element.turns_with_sign)
                    * polygon_greens(coordinate[:, 0], coordinate[:, 1], vertices)[0]
                )
            current = np.asarray(coil.current.data, dtype=float)
            maximum_current = float(np.nanmax(np.abs(current)))
            envelope = np.abs(nova_total_flux_to_corpus(response)) * maximum_current
            contributions.append(
                {
                    "coil": name,
                    "element_count": len(coil.element),
                    "maximum_reference_current_a": maximum_current,
                    "maximum_envelope_wb_per_radian": float(np.max(envelope)),
                    "rms_envelope_wb_per_radian": float(np.sqrt(np.mean(envelope**2))),
                    "envelope_samples_wb_per_radian": envelope,
                }
            )
    combined = np.sum(
        [item.pop("envelope_samples_wb_per_radian") for item in contributions], axis=0
    )
    combined_rms = float(np.sqrt(np.mean(combined**2)))
    ratio = combined_rms / measured_rms_wb_per_radian
    return {
        "coils": contributions,
        "comparison": (
            "sum of absolute per-coil boundary responses at each coil's maximum "
            "current in the independent netCDF pulse; an intentionally generous "
            "order-of-magnitude envelope, not a fit or a current assignment"
        ),
        "reference_limitations": (
            "the netCDF pulse is not a competition shot and its producer carries "
            "a documented family-specific current-scale inconsistency"
        ),
        "measured_gauged_boundary_rms_wb_per_radian": measured_rms_wb_per_radian,
        "combined_envelope_rms_wb_per_radian": combined_rms,
        "envelope_to_discrepancy_ratio": ratio,
        "could_account_in_magnitude": bool(ratio >= 0.1),
        "interpretation": (
            "within one order of magnitude"
            if ratio >= 0.1
            else "more than one order short"
        ),
        "fitted": False,
    }


def _pooled_metrics(records: list[dict[str, Any]], key: str) -> dict[str, float]:
    values = np.asarray(
        [record["residuals"][key]["fractional_rms"] for record in records],
        dtype=float,
    )
    return {
        "minimum": float(np.min(values)),
        "median": float(np.median(values)),
        "maximum": float(np.max(values)),
    }


def summarize(records: list[dict[str, Any]]) -> dict[str, Any]:
    """Build the pooled attribution without dropping any frame."""

    fixed = _pooled_metrics(records, "fixed_boundary_profile")
    free = _pooled_metrics(records, "free_boundary_profile")
    vacuum = _pooled_metrics(records, "free_minus_fixed_vacuum_difference")
    boundary = np.asarray(
        [
            record["boundary_flux_discrepancy"]["after_gauge"][
                "fractional_rms_of_labelled_range"
            ]
            for record in records
        ]
    )
    attribution = component_verdict(
        fixed["median"], vacuum["median"], float(np.median(boundary))
    )
    return {
        "frames": len(records),
        "root_find_performed": False,
        "all_frames_evaluated_at_label": all(
            record["evaluation_point"] == "labelled psi map unchanged"
            for record in records
        ),
        "residual_fractional_rms": {
            "direct_operator_fixed_boundary_control": _pooled_metrics(
                records, "direct_operator_fixed_boundary_control"
            ),
            "fixed_boundary_profile": fixed,
            "free_boundary_profile": free,
            "free_minus_fixed_vacuum_difference": vacuum,
        },
        "gauged_boundary_fractional_rms": {
            "minimum": float(np.min(boundary)),
            "median": float(np.median(boundary)),
            "maximum": float(np.max(boundary)),
        },
        "attribution": attribution,
        "nearby_root_frames": sum(record["nearby_root_admitted"] for record in records),
        "pooled_nearby_root_admitted": bool(
            free["median"] <= NEARBY_ROOT_MAXIMUM_FRACTIONAL_RMS
        ),
    }


def run_completion(
    selected_count: int,
    completed_count: int,
    started_at: str,
    finished_at: str,
) -> dict[str, Any]:
    """Record that one cohort run selected and completed every required frame."""

    if selected_count != FRAME_COUNT:
        raise RuntimeError(
            f"root-existence run selected {selected_count} of {FRAME_COUNT} frames"
        )
    if completed_count != selected_count:
        raise RuntimeError(
            f"root-existence run completed {completed_count} of {selected_count} frames"
        )
    return {
        "started_at_utc": started_at,
        "finished_at_utc": finished_at,
        "frame_count_at_start": {
            "selected": selected_count,
            "required": FRAME_COUNT,
            "display": f"{selected_count} of {FRAME_COUNT}",
        },
        "frame_count_at_end": {
            "completed": completed_count,
            "required": FRAME_COUNT,
            "display": f"{completed_count} of {FRAME_COUNT}",
        },
    }


def residual_figure(fields: dict[str, np.ndarray], path: Path) -> None:
    """Plot fixed, free, and vacuum-attributed residual contours."""

    radius = fields["radius"]
    height = fields["height"]
    entries = (
        ("Fixed boundary", fields["fixed_residual_per_radian"]),
        ("Free boundary", fields["free_residual_per_radian"]),
        ("Free minus fixed", fields["vacuum_difference_per_radian"]),
    )
    figure, axes = plt.subplots(1, 3, figsize=(10.2, 4.2), sharex=True, sharey=True)
    for axis, (title, field) in zip(axes, entries, strict=True):
        maximum = float(np.max(np.abs(field)))
        levels = np.linspace(-maximum, maximum, 13)
        if maximum > 0.0:
            axis.contour(
                radius,
                height,
                field.T,
                levels=levels,
                colors="#777777",
                linewidths=0.5,
            )
        axis.contour(
            radius,
            height,
            fields["core"].T.astype(float),
            levels=[0.5],
            colors="#cc0000",
            linewidths=0.9,
        )
        axis.set_title(f"{title}\nmax |r|={maximum:.3g} Wb/rad")
        axis.set_xlabel("R [m]")
        axis.set_aspect("equal")
    axes[0].set_ylabel("Z [m]")
    figure.tight_layout()
    figure.savefig(path, dpi=180)
    plt.close(figure)


def boundary_figure(fields: dict[str, np.ndarray], path: Path) -> None:
    """Plot the gauged border discrepancy in physical space and arclength."""

    coordinate = fields["border_coordinate"]
    difference = fields["border_difference"]
    segment = np.linalg.norm(
        np.diff(np.vstack([coordinate, coordinate[:1]]), axis=0), axis=1
    )
    arclength = np.r_[0.0, np.cumsum(segment[:-1])]
    scale = np.max(np.abs(difference))
    size = 8.0 + 40.0 * np.abs(difference) / max(scale, np.finfo(float).tiny)
    figure, axes = plt.subplots(1, 2, figsize=(9.4, 4.0))
    axes[0].contour(
        fields["radius"],
        fields["height"],
        fields["label_total"].T,
        levels=12,
        colors="#999999",
        linewidths=0.4,
    )
    axes[0].plot(
        np.r_[coordinate[:, 0], coordinate[0, 0]],
        np.r_[coordinate[:, 1], coordinate[0, 1]],
        color="#222222",
        linewidth=0.7,
    )
    axes[0].scatter(
        coordinate[:, 0],
        coordinate[:, 1],
        s=size,
        facecolors="none",
        edgecolors="#444444",
        linewidths=0.45,
    )
    axes[0].set(
        xlabel="R [m]",
        ylabel="Z [m]",
        title="Grid border; marker size is |discrepancy|",
    )
    axes[0].set_aspect("equal")
    axes[1].axhline(0.0, color="#222222", linewidth=0.6)
    axes[1].plot(arclength, difference, color="#666666", linewidth=0.8)
    axes[1].set(
        xlabel="Clockwise border arclength [m]",
        ylabel="Label minus gauged coil psi [Wb/rad]",
        title="Boundary flux discrepancy",
    )
    figure.tight_layout()
    figure.savefig(path, dpi=180)
    plt.close(figure)


def run(data: Path, output: Path) -> dict[str, Any]:
    """Evaluate the preregistered cohort and publish receipt and figures."""

    preregistration_path = write_preregistration(output)
    preregistration_digest = require_preregistration(preregistration_path)
    selected = select_frames(sorted(data.glob("*.parquet")), FRAME_COUNT)
    started_at = datetime.now(UTC).isoformat()
    print(f"STARTED {len(selected)}/{FRAME_COUNT} selected frames", flush=True)
    first_columns = _LABEL_COLUMNS + _GEOMETRY_COLUMNS + _CURRENT_COLUMNS
    first_row = _read(selected[0].path, first_columns)
    radius, height = canonical_axes(first_row)
    plasma_response = filament_response(radius, height)
    records = []
    first_fields: dict[str, np.ndarray] | None = None
    for index, chosen in enumerate(selected, start=1):
        row = first_row if index == 1 else _read(chosen.path, first_columns)
        row["_source_path"] = str(chosen.path)
        record, fields = evaluate_frame(row, chosen.frame, plasma_response)
        records.append(record)
        if first_fields is None:
            first_fields = fields
        free_fraction = record["residuals"]["free_boundary_profile"]["fractional_rms"]
        print(
            f"EVALUATED {index}/{len(selected)} {record['shot']}:{record['frame']} "
            f"free_fractional_rms={free_fraction:.6e} "
            f"verdict={record['attribution']['verdict']}",
            flush=True,
        )
    assert first_fields is not None
    measured_boundary_rms = records[0]["boundary_flux_discrepancy"]["after_gauge"][
        "rms_wb_per_radian"
    ]
    omitted = omitted_coil_envelope(
        first_fields["border_coordinate"], measured_boundary_rms
    )
    completion = run_completion(
        len(selected),
        len(records),
        started_at,
        datetime.now(UTC).isoformat(),
    )
    receipt = {
        "preregistration": preregistration(),
        "preregistration_path": str(preregistration_path),
        "preregistration_sha256": preregistration_digest,
        "result": {
            "measurement": "DIII-D labelled-map root-existence residual attribution",
            "no_root_find": True,
            "no_fitting": True,
            "coil_currents_adjusted": False,
            "run_completion": completion,
            "frames": records,
            "pooled": summarize(records),
            "omitted_coil_magnitude_comparison": omitted,
        },
    }
    receipt_path = output / RECEIPT_NAME
    receipt_path.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    residual_figure(first_fields, output / RESIDUAL_FIGURE_NAME)
    boundary_figure(first_fields, output / BOUNDARY_FIGURE_NAME)
    return receipt


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--preregister-only", action="store_true")
    arguments = parser.parse_args()
    path = write_preregistration(arguments.output)
    print(f"PREREGISTERED {path}", flush=True)
    if arguments.preregister_only:
        return
    receipt = run(arguments.data, arguments.output)
    print(json.dumps(receipt["result"]["pooled"], indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
