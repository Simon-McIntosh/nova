def _git(*arguments: str) -> str:
    """Return one source-tree identity fact."""

    return subprocess.check_output(
        ["git", *arguments], text=True, stderr=subprocess.DEVNULL
    ).strip()


def _digest(path: Path) -> str:
    """Return one artifact digest."""

    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read(path: Path) -> dict[str, Any]:
    """Load one banked JSON authority."""

    return json.loads(path.read_text())


def _difference(left: Any, right: Any) -> float:
    """Return the finite sup-norm difference between two states."""

    eager = np.asarray(left, dtype=np.float64)
    compiled = np.asarray(right, dtype=np.float64)
    finite = np.isfinite(eager) & np.isfinite(compiled)
    return float(np.max(np.abs(compiled[finite] - eager[finite])))


def _normalise(vector: np.ndarray) -> np.ndarray:
    """Return a unit two-norm vector, preserving an exact zero."""

    norm = float(np.linalg.norm(vector))
    return vector if norm == 0.0 else vector / norm


def _production_prefix_trajectory(profile, initial_flux, target_current):
    """Return eager and compiled production terminals after every prefix."""

    eager_states: list[np.ndarray] = [np.asarray(initial_flux, dtype=np.float64)]
    compiled_states: list[np.ndarray] = [np.asarray(initial_flux, dtype=np.float64)]
    rows: list[dict[str, Any]] = []
    preceding: float | None = None
    for update in range(1, NONLINEAR_UPDATES + 1):
        eager, compiled = _solve_pair(profile, initial_flux, target_current, update)
        eager_state = np.asarray(eager.flux, dtype=np.float64)
        compiled_state = np.asarray(compiled.flux, dtype=np.float64)
        separation = _difference(eager_state, compiled_state)
        growth = (
            None if preceding is None or preceding == 0.0 else separation / preceding
        )
        rows.append(
            {
                "nonlinear_update": update,
                "maximum_absolute_separation": separation,
                "growth_from_preceding_update": growth,
                "eager_residual": float(eager.fixed_point.residual),
                "compiled_residual": float(compiled.fixed_point.residual),
            }
        )
        eager_states.append(eager_state)
        compiled_states.append(compiled_state)
        preceding = separation
    return eager_states, compiled_states, rows


def _arnoldi_event(map_fn, state: np.ndarray, incoming: np.ndarray) -> dict[str, Any]:
    """Measure the exact tangent on its production residual Krylov space."""

    state_device = jnp.asarray(state)

    @jax.jit
    def map_and_tangent(vector):
        mapped, tangent = jax.jvp(map_fn, (state_device,), (vector,))
        return mapped, tangent

    mapped = np.asarray(map_fn(state_device), dtype=np.float64)
    residual = mapped - state
    residual_norm = float(np.linalg.norm(residual))
    if residual_norm == 0.0:
        raise RuntimeError("the production residual cannot seed an Arnoldi space")

    basis: list[np.ndarray] = [_normalise(residual)]
    hessenberg = np.zeros((KRYLOV_DIMENSION + 1, KRYLOV_DIMENSION))
    for column in range(KRYLOV_DIMENSION):
        vector = jnp.asarray(basis[column])
        _mapped, tangent = map_and_tangent(vector)
        action = np.array(vector - tangent, dtype=np.float64, copy=True)
        for row, basis_vector in enumerate(basis):
            coefficient = float(np.dot(basis_vector, action))
            hessenberg[row, column] += coefficient
            action -= coefficient * basis_vector
        # A second pass keeps the small projected condition meaningful.
        for row, basis_vector in enumerate(basis):
            correction = float(np.dot(basis_vector, action))
            hessenberg[row, column] += correction
            action -= correction * basis_vector
        next_norm = float(np.linalg.norm(action))
        hessenberg[column + 1, column] = next_norm
        if column + 1 < KRYLOV_DIMENSION:
            if next_norm <= 64.0 * np.finfo(np.float64).eps:
                raise RuntimeError("the production Krylov space broke down early")
            basis.append(action / next_norm)

    action_singular = np.linalg.svd(hessenberg, compute_uv=False)
    action_condition = float(action_singular[0] / action_singular[-1])
    projected_action = hessenberg[:KRYLOV_DIMENSION, :]
    projected_map = np.eye(KRYLOV_DIMENSION) - projected_action
    map_singular = np.linalg.svd(projected_map, compute_uv=False)
    operator_norm = float(map_singular[0])

    _u, _s, right = np.linalg.svd(hessenberg, full_matrices=False)
    near_singular_coordinates = right[-1]
    basis_matrix = np.stack(basis, axis=1)
    active_direction = _normalise(basis_matrix @ near_singular_coordinates)
    incoming_direction = _normalise(np.asarray(incoming, dtype=np.float64))
    incoming_overlap = float(abs(np.dot(active_direction, incoming_direction)))
    residual_overlap = float(abs(near_singular_coordinates[0]))
    return {
        "projected_coupled_map_operator_norm": operator_norm,
        "projected_krylov_action_condition_number": action_condition,
        "projected_krylov_action_largest_singular_value": float(action_singular[0]),
        "projected_krylov_action_smallest_singular_value": float(action_singular[-1]),
        "incoming_separation_active_mode_overlap": incoming_overlap,
        "residual_active_mode_overlap": residual_overlap,
        "nonlinear_residual_l2": residual_norm,
        "arnoldi_dimension": KRYLOV_DIMENSION,
    }


def _attach_events(profile, target_current, eager_states, compiled_states, trajectory):
    """Attach local tangent and Krylov evidence to every production update."""

    map_fn = profile.flux_map(target_current=target_current)
    cumulative_norm_product = 1.0
    rows: list[dict[str, Any]] = []
    first_map_eager = np.asarray(map_fn(jnp.asarray(eager_states[0])))
    first_map_compiled = np.asarray(jax.jit(map_fn)(jnp.asarray(eager_states[0])))
    injected = first_map_compiled - first_map_eager
    for index, trajectory_row in enumerate(trajectory):
        incoming = (
            injected if index == 0 else compiled_states[index] - eager_states[index]
        )
        event = _arnoldi_event(map_fn, eager_states[index], incoming)
        cumulative_norm_product *= event["projected_coupled_map_operator_norm"]
        growth = trajectory_row["growth_from_preceding_update"]
        rows.append(
            {
                **trajectory_row,
                **event,
                "cumulative_product_of_trajectory_operator_norms": (
                    cumulative_norm_product
                ),
                "burst": bool(growth is not None and growth >= BURST_GROWTH_FLOOR),
            }
        )
    return rows


def _event_discrimination(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Name the event variable that discriminates burst from quiet updates."""

    measurable = [row for row in rows if row["growth_from_preceding_update"]]
    bursts = [row for row in measurable if row["burst"]]
    quiet = [row for row in measurable if not row["burst"]]
    growth = np.log10([row["growth_from_preceding_update"] for row in measurable])
    condition = np.log10(
        [row["projected_krylov_action_condition_number"] for row in measurable]
    )
    overlap = [row["incoming_separation_active_mode_overlap"] for row in measurable]
    condition_correlation = float(spearmanr(growth, condition).statistic)
    overlap_correlation = float(spearmanr(growth, overlap).statistic)
    burst_condition = float(
        np.median([row["projected_krylov_action_condition_number"] for row in bursts])
    )
    quiet_condition = float(
        np.median([row["projected_krylov_action_condition_number"] for row in quiet])
    )
    burst_overlap = float(
        np.median([row["incoming_separation_active_mode_overlap"] for row in bursts])
    )
    quiet_overlap = float(
        np.median([row["incoming_separation_active_mode_overlap"] for row in quiet])
    )

    condition_discriminates = (
        burst_condition >= 2.0 * quiet_condition and condition_correlation >= 0.5
    )
    alignment_discriminates = (
        burst_overlap >= 1.5 * max(quiet_overlap, np.finfo(float).tiny)
        and overlap_correlation >= 0.5
    )
    if condition_discriminates:
        mechanism = "KRYLOV_CONDITIONED_NON_NORMAL_EVENT"
        discriminator = (
            "Burst updates carry both a larger projected (I-J) condition and "
            "a positive rank correlation between condition and separation growth."
        )
    elif alignment_discriminates:
        mechanism = "ACTIVE_MODE_ALIGNMENT_NON_NORMAL_EVENT"
        discriminator = (
            "Burst updates align the incoming representation difference with "
            "the iteration-local near-singular Krylov direction."
        )
    else:
        mechanism = "TRAJECTORY_VARYING_NON_NORMAL_TRANSIENT"
        discriminator = (
            "No single Krylov condition or overlap threshold separates every "
            "burst; the varying iteration-local operator product is the retained "
            "mechanism and a frozen terminal eigenpair is excluded."
        )
    return {
        "mechanism": mechanism,
        "discriminator": discriminator,
        "burst_growth_floor": BURST_GROWTH_FLOOR,
        "burst_updates": [row["nonlinear_update"] for row in bursts],
        "quiet_updates": [row["nonlinear_update"] for row in quiet],
        "spearman_log_growth_vs_log_krylov_condition": condition_correlation,
        "spearman_log_growth_vs_active_mode_overlap": overlap_correlation,
        "burst_median_krylov_condition": burst_condition,
        "quiet_median_krylov_condition": quiet_condition,
        "burst_to_quiet_condition_ratio": burst_condition / quiet_condition,
        "burst_median_active_mode_overlap": burst_overlap,
        "quiet_median_active_mode_overlap": quiet_overlap,
        "burst_to_quiet_overlap_ratio": burst_overlap
        / max(quiet_overlap, np.finfo(float).tiny),
    }


def _alternate_seed(profile, target_current: float, store: Path) -> np.ndarray:
    """Return a same-shot seed displaced by a real neighbouring LCFS direction."""

    shot, _row = TRAJECTORY_CASE
    group = zarr.open_group(str(store / f"{shot}.zarr"), mode="r")["efm"]
    boundary = _stored_lcfs(group, ALTERNATE_SEED_ROW)
    return np.asarray(profile.moment_seed(boundary, target_current).flux)


def _seed_prediction(baseline, alternate, baseline_seed, alternate_seed):
    """Test whether a physically distinct seed direction moves burst events."""

    baseline_bursts = [
        row["nonlinear_update"]
        for row in baseline
        if row["growth_from_preceding_update"] is not None
        and row["growth_from_preceding_update"] >= BURST_GROWTH_FLOOR
    ]
    alternate_bursts = [
        row["nonlinear_update"]
        for row in alternate
        if row["growth_from_preceding_update"] is not None
        and row["growth_from_preceding_update"] >= BURST_GROWTH_FLOOR
    ]
    seed_delta = np.asarray(alternate_seed) - np.asarray(baseline_seed)
    return {
        "prediction": "a different seed direction moves bursts to other updates",
        "construction": (
            f"same {TRAJECTORY_CASE[0]}/{TRAJECTORY_CASE[1]} profile and target "
            f"current; moment seed uses the real LCFS at row {ALTERNATE_SEED_ROW}"
        ),
        "seed_direction_l2": float(np.linalg.norm(seed_delta)),
        "seed_direction_peak": float(np.max(np.abs(seed_delta))),
        "baseline_burst_updates": baseline_bursts,
        "alternate_burst_updates": alternate_bursts,
        "bursts_moved": baseline_bursts != alternate_bursts,
        "supported": baseline_bursts != alternate_bursts,
        "baseline_cumulative_separation_growth": baseline[-1][
            "maximum_absolute_separation"
        ]
        / baseline[0]["maximum_absolute_separation"],
        "alternate_cumulative_separation_growth": alternate[-1][
            "maximum_absolute_separation"
        ]
        / alternate[0]["maximum_absolute_separation"],
    }


def _warm_prediction(attribution: dict[str, Any], warm: dict[str, Any]):
    """Join the pre-existing warm outcome to its banked amplification metric."""

    amplification = {
        (int(row["shot"]), int(row["slice_index"])): float(
            row["solved_flux"]["maximum_absolute_difference"]
            / row["single_map_application"]["maximum_absolute_difference"]
        )
        for row in attribution["current_source_measurement"]["cases"]
    }
    frames = []
    for row in warm["references"]:
        key = (int(row["reference"]["shot"]), int(row["reference"]["slice_index"]))
        cold_residual = float(row["cold_control"]["terminal_fixed_point_residual"])
        warm_residual = float(row["warm_solve"]["terminal_fixed_point_residual"])
        frames.append(
            {
                "shot": key[0],
                "slice_index": key[1],
                "warm_residual_over_cold": warm_residual / cold_residual,
                "warm_improved": warm_residual < cold_residual,
                "banked_one_map_to_terminal_separation_growth": amplification[key],
            }
        )
    improved = [
        row["banked_one_map_to_terminal_separation_growth"]
        for row in frames
        if row["warm_improved"]
    ]
    worsened = [
        row["banked_one_map_to_terminal_separation_growth"]
        for row in frames
        if not row["warm_improved"]
    ]
    improved_median = float(np.median(improved))
    worsened_median = float(np.median(worsened))
    return {
        "prediction": (
            "warm-improved frames have smaller cumulative representation-"
            "separation growth than warm-worsened frames"
        ),
        "metric": (
            "banked terminal eager/compiled separation divided by the banked "
            "one-map separation on the same frame"
        ),
        "frames": frames,
        "improved_count": len(improved),
        "worsened_count": len(worsened),
        "improved_group_median_growth": improved_median,
        "worsened_group_median_growth": worsened_median,
        "worsened_over_improved_median": worsened_median / improved_median,
        "supported_by_group_median": improved_median < worsened_median,
        "qualification": (
            "The group median tests the banked prediction; individual ordering "
            "is mixed and the improved 21985/51 frame remains the largest-growth "
            "outlier."
        ),
    }


