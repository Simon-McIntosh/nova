def _render(receipt: dict[str, Any], path: Path) -> None:
    """Render separation, event, and independent-prediction evidence."""

    rows = receipt["trajectory"]["iterations"]
    alternate = receipt["predictions"]["different_seed_direction"][
        "alternate_trajectory"
    ]
    updates = np.asarray([row["nonlinear_update"] for row in rows])
    growth = np.asarray(
        [
            np.nan
            if row["growth_from_preceding_update"] is None
            else row["growth_from_preceding_update"]
            for row in rows
        ]
    )
    alternate_growth = np.asarray(
        [
            np.nan
            if row["growth_from_preceding_update"] is None
            else row["growth_from_preceding_update"]
            for row in alternate
        ]
    )
    condition = np.asarray(
        [row["projected_krylov_action_condition_number"] for row in rows]
    )
    overlap = np.asarray(
        [row["incoming_separation_active_mode_overlap"] for row in rows]
    )

    figure, axes = plt.subplots(1, 3, figsize=(15.0, 4.4), constrained_layout=True)
    axes[0].semilogy(updates, growth, "o-", label="production seed")
    axes[0].semilogy(updates, alternate_growth, "s--", label="alternate direction")
    axes[0].axhline(BURST_GROWTH_FLOOR, color="black", ls=":", lw=1)
    axes[0].set(
        title="Representation-separation events",
        xlabel="Newton update",
        ylabel="growth from preceding update",
    )
    axes[0].legend(fontsize=8)

    axes[1].semilogy(
        updates, condition, "o-", color="tab:red", label="cond(I-J), Krylov"
    )
    twin = axes[1].twinx()
    twin.plot(updates, overlap, "s-", color="tab:blue", label="active-mode overlap")
    axes[1].set(
        title="Iteration-local event coordinates",
        xlabel="Newton update",
        ylabel="projected action condition",
    )
    twin.set_ylabel("incoming separation overlap")
    handles = axes[1].lines + twin.lines
    axes[1].legend(handles, [line.get_label() for line in handles], fontsize=8)

    warm = receipt["predictions"]["warm_ladder_directionality"]
    for row in warm["frames"]:
        colour = "tab:green" if row["warm_improved"] else "tab:orange"
        marker = "o" if row["warm_improved"] else "X"
        axes[2].scatter(
            row["warm_residual_over_cold"],
            row["banked_one_map_to_terminal_separation_growth"],
            color=colour,
            marker=marker,
            s=55,
        )
        axes[2].annotate(
            str(row["shot"]),
            (
                row["warm_residual_over_cold"],
                row["banked_one_map_to_terminal_separation_growth"],
            ),
            fontsize=7,
        )
    axes[2].axvline(1.0, color="black", ls=":", lw=1)
    axes[2].set_yscale("log")
    axes[2].set(
        title="Pre-banked warm prediction",
        xlabel="warm / cold terminal residual",
        ylabel="one-map to terminal growth",
    )
    for axis in axes:
        axis.grid(True, which="both", alpha=0.25)
    figure.suptitle(receipt["verdict"]["mechanism"].replace("_", " "))
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(path, dpi=190)
    plt.close(figure)


